#!/usr/bin/env python3
"""Inspect the actual signed release files. No signing, key access, or publication."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import time

import apk_delta
from release_deltas import version_tuple

ROOT = Path(__file__).resolve().parents[1]
BASE_VERSION = '0.4.100'
BASE_CODE = 125
PACKAGE = 'dev.jun.gyeot'
ABIS = {'armeabi-v7a', 'arm64-v8a', 'x86_64'}
EVIDENCE_PREFIX = 'RELEASE_CANDIDATE_JSON='
DELTA_FIELDS = ('name', 'format', 'abi', 'baseVersion', 'targetVersion', 'baseSha256',
                'targetSha256', 'targetSize', 'patchSha256', 'patchSize', 'reusedBytes', 'operations')


def command(arguments):
    """Only public APK inspection output; never echo subprocess errors or arguments."""
    try:
        result = subprocess.run([str(value) for value in arguments], capture_output=True,
                                text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired):
        raise ValueError('APK inspection command unavailable or timed out') from None
    if result.returncode:
        raise ValueError('APK inspection command failed')
    return result.stdout


def source_version(path):
    source = Path(path).read_text()
    name = re.findall(r"\bversionName\s+'([^']+)'", source)
    code = re.findall(r'\bversionCode\s+(\d+)\b', source)
    if len(name) != 1 or len(code) != 1:
        raise ValueError('Ambiguous source version')
    version_tuple(name[0])
    return name[0], int(code[0])


def manifest_version(text):
    rows = re.findall(r'^package: (.+)$', text, re.MULTILINE)
    if len(rows) != 1:
        raise ValueError('APK manifest package metadata missing or ambiguous')
    fields = {}
    for key in ('name', 'versionCode', 'versionName'):
        values = re.findall(r"(?:^|\s)" + key + r"='([^']*)'", rows[0])
        if len(values) != 1:
            raise ValueError('APK manifest version metadata missing or ambiguous')
        fields[key] = values[0]
    if not re.fullmatch(r'\d+', fields['versionCode']):
        raise ValueError('APK version code is invalid')
    version_tuple(fields['versionName'])
    return fields['name'], fields['versionName'], int(fields['versionCode'])


def inspect_apk(path, tools, expected_version, expected_code, pin, expected_abis):
    path = Path(path)
    size = apk_delta._size(path)
    identity = manifest_version(command([tools / 'aapt2', 'dump', 'badging', path]))
    if identity != (PACKAGE, expected_version, expected_code):
        raise ValueError('Actual APK package/version differs from the source candidate')
    signatures = command([tools / 'apksigner', 'verify', '--verbose', '--print-certs', path])
    signers = re.findall(r'^Signer #\d+ certificate SHA-256 digest:\s*([0-9a-fA-F]{64})\s*$',
                         signatures, re.MULTILINE)
    if len(signers) != 1 or signers[0].lower() != pin:
        raise ValueError('APK signer differs from the existing pinned signer')
    entries = apk_delta._payloads(path, time.monotonic() + apk_delta.TIMEOUT)
    required = {'AndroidManifest.xml', 'classes.dex', 'assets/browser/manifest.json',
                'assets/browser/content.js'}
    actual_abis = {name.split('/')[1] for name in entries if name.startswith('lib/') and len(name.split('/')) > 2}
    if actual_abis != expected_abis:
        raise ValueError('Actual APK native ABI set differs from its advertised variant')
    for abi in expected_abis:
        required.update('lib/' + abi + '/' + name for name in ('libxul.so', 'libmozglue.so', 'libgyeot_trash.so'))
    if not required.issubset(entries):
        raise ValueError('Actual APK is missing required code, browser assets, or native libraries')
    return {'name': path.name, 'sha256': apk_delta.digest(path).hex(), 'size': size,
            'package': identity[0], 'versionName': identity[1], 'versionCode': identity[2],
            'signerSha256': pin, 'abis': sorted(actual_abis)}


def inspect_delta(path, row, target):
    """Recheck exact generated bytes and bounded wire structure; generation already reconstructed the base."""
    size = apk_delta._size(path)
    digest = apk_delta.digest(path).hex()
    if row.get('patchSize') != size or row.get('patchSha256') != digest:
        raise ValueError('Delta bytes differ from the verified generation report')
    deadline = time.monotonic() + apk_delta.TIMEOUT
    with apk_delta._GzipReader(path) as delta:
        if apk_delta._read(delta, 8) != apk_delta.MAGIC:
            raise ValueError('Unknown delta format')
        base = apk_delta._read(delta, 32).hex()
        goal = apk_delta._read(delta, 32).hex()
        target_size = apk_delta._u64(delta)
        if (base != row.get('baseSha256') or goal != target['sha256'] or target_size != target['size']
                or goal != row.get('targetSha256') or target_size != row.get('targetSize')):
            raise ValueError('Delta target does not match the actual signed phone APK')
        written = operations = reused = 0
        while True:
            apk_delta._guard(deadline, None)
            operation = apk_delta._read(delta, 1)[0]
            if operation == 2:
                break
            operations += 1
            if operations > apk_delta.MAX_OPERATIONS:
                raise ValueError('Too many delta operations')
            if operation == 0:
                offset, length = apk_delta._u64(delta), apk_delta._u64(delta)
                if offset > apk_delta.MAX_APK or length > apk_delta.MAX_APK - offset:
                    raise ValueError('Delta copy range exceeds the supported base APK size')
                reused += length
            elif operation == 1:
                length = apk_delta._u64(delta)
            else:
                raise ValueError('Unknown delta operation')
            if length == 0 or length > target_size - written:
                raise ValueError('Delta operation exceeds the target APK size')
            written += length
            if operation == 1:
                remaining = length
                while remaining:
                    apk_delta._guard(deadline, None)
                    count = min(apk_delta.CHUNK, remaining)
                    apk_delta._read(delta, count)
                    remaining -= count
        if written != target_size or delta.read(1):
            raise ValueError('Delta length or trailing bytes invalid')
    if row.get('operations') != operations or row.get('reusedBytes') != reused:
        raise ValueError('Delta operations differ from the verified generation report')
    # Evidence is public. Never copy unrecognized report fields into the file or CI log.
    return {field: row[field] for field in DELTA_FIELDS}


def inspect_deltas(directory, report, target, version):
    directory, report = Path(directory), Path(report)
    if report.stat().st_size > 1024 * 1024:
        raise ValueError('Delta report too large')
    payload = json.loads(report.read_text())
    rows = payload.get('deltas') if isinstance(payload, dict) else None
    if not isinstance(rows, list) or len(rows) > 2 or any(not isinstance(row, dict) for row in rows):
        raise ValueError('Delta report is invalid')
    names = []
    for row in rows:
        base = row.get('baseSha256')
        if not isinstance(base, str) or not re.fullmatch('[0-9a-f]{64}', base):
            raise ValueError('Delta base checksum missing')
        name = 'gyeot-' + version + '-arm64-from-' + base + '.gdelta'
        if row.get('name') != name or row.get('targetVersion') != version or row.get('abi') != 'arm64-v8a':
            raise ValueError('Delta update filename or version disagrees with the candidate')
        if row.get('format') != 'gyeot-delta-v1' or version_tuple(row.get('baseVersion')) >= version_tuple(version):
            raise ValueError('Delta base version or format invalid')
        names.append(name)
    actual = {path.name for path in directory.glob('*.gdelta')}
    if len(names) != len(set(names)) or actual != set(names):
        raise ValueError('Unexpected, missing, duplicate, or stale delta update files')
    return [inspect_delta(directory / row['name'], row, target) for row in rows]


def verify(gradle, pin_file, tools, build, delta_report, commit):
    if not isinstance(commit, str) or not re.fullmatch('[0-9a-f]{40}', commit):
        raise ValueError('Exact source commit required')
    version, code = source_version(gradle)
    if version_tuple(version) <= version_tuple(BASE_VERSION) or not BASE_CODE < code <= 2100000000:
        raise ValueError('Candidate must be newer than 0.4.100 / 125')
    pin = Path(pin_file).read_text().strip()
    if not re.fullmatch('[0-9a-f]{64}', pin):
        raise ValueError('Existing pinned signer fingerprint is missing or invalid')
    build, tools = Path(build), Path(tools)
    phone = inspect_apk(build / ('gyeot-' + version + '-debug.apk'), tools, version, code, pin, {'arm64-v8a'})
    universal = inspect_apk(build / ('gyeot-' + version + '-universal-debug.apk'), tools, version, code, pin, ABIS)
    deltas = inspect_deltas(build / 'deltas', delta_report, phone, version)
    return {'sourceCommit': commit, 'baselineVersionName': BASE_VERSION, 'baselineVersionCode': BASE_CODE,
            'apks': [phone, universal], 'deltas': deltas,
            'deltaVerification': 'Generator reconstructed each reported patch; this gate rechecked exact patch bytes, target and wire structure.'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--commit', required=True)
    parser.add_argument('--delta-report', type=Path, default=ROOT / 'build/delta-report.json')
    parser.add_argument('--output', type=Path, default=ROOT / 'build/release-candidate.json')
    args = parser.parse_args()
    if command(['git', '-C', ROOT, 'rev-parse', 'HEAD']).strip() != args.commit:
        raise ValueError('Candidate evidence commit differs from the checked-out source')
    cache = Path(os.environ.get('GYEOT_BUILD_CACHE', ROOT / '.cache'))
    evidence = verify(ROOT / 'app/build.gradle', ROOT / 'tools/signing-cert.sha256',
                      cache / 'build-tools/35.0.0', ROOT / 'build', args.delta_report, args.commit)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(evidence, indent=2, sort_keys=True) + '\n')
    # Keep verified public metadata in the CI log and release-attached JSON without
    # depending on GitHub Actions artifact storage.
    print(EVIDENCE_PREFIX + json.dumps(evidence, sort_keys=True, separators=(',', ':')))


if __name__ == '__main__':
    main()
